def logo_parts(svg: Path) -> dict:
    text = svg.read_text()
    parts = {"wordmark": [], "symbol": None, "transform": None}
    group = re.search(r'<g transform="translate\(([\d.]+),([\d.]+)\) scale\(([\d.]+)\)">\s*<path d="([^"]+)" fill="#0E7490"/>', text)
    if group:
        parts["transform"] = tuple(float(v) for v in group.group(1, 2, 3))
        parts["symbol"] = group.group(4)
    for match in re.finditer(r'<path d="([^"]+)" fill="#14232B"/>', text):
        parts["wordmark"].append(match.group(1))
    return parts


def brand_cs(symbol: str, en: dict, ar: dict) -> str:
    def lit(s: str) -> str:
        return '"' + s + '"'

    def lockup(name: str, p: dict) -> str:
        tx, ty, sc = p["transform"]
        return (f"    /// <summary>The {name} lock-up, 674×200: the wordmark paths and where the symbol sits.</summary>\n"
                f"    public static readonly LockupGeometry {name} = new(\n"
                f"        new[]\n        {{\n" + "".join(f"            {lit(d)},\n" for d in p["wordmark"]) +
                f"        }},\n        SymbolX: {tx}, SymbolY: {ty}, SymbolScale: {sc});\n")

    return (f"// <auto-generated>{HEADER}</auto-generated>\n"
            "namespace Josour.Brand.Controls;\n\n"
            "/// <summary>A lock-up: its wordmark paths (ink) and the symbol's placement (translate, then scale).</summary>\n"
            "public sealed record LockupGeometry(string[] Wordmark, double SymbolX, double SymbolY, double SymbolScale)\n"
            "{\n    public const double Width = 674;\n    public const double Height = 200;\n}\n\n"
            "/// <summary>The qantara mark from <c>1-qantara/</c>, path for path. Never redrawn: regenerate instead.</summary>\n"
            "public static class BrandGeometry\n{\n"
            "    /// <summary>The symbol on its 24-unit grid: the arch (outer r 9, inner r 6 about 12,15) and two dots of r 2.25.</summary>\n"
            f"    public const string Symbol = {lit(symbol)};\n\n"
            + lockup("EnglishFirst", en) + "\n" + lockup("ArabicFirst", ar) + "}\n")


