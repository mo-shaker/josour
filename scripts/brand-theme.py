def argb(hex_rgb: str, alpha: str = "FF") -> str:
    h = hex_rgb.lstrip("#").upper()
    return "#" + h if len(h) == 8 else "#" + alpha + h


def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


