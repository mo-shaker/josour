class Canvas:
    """An RGBA image drawn supersampled and reduced, so edges are anti-aliased the way a vector renderer would: 16× for
    icon sizes, less for the large images so the work stays small."""

    def __init__(self, w, h, bg=(0, 0, 0, 0)):
        from PIL import Image
        self.Image = Image
        self.w, self.h = w, h
        self.ss = max(2, min(16, 2048 // max(w, h)))
        self.img = Image.new("RGBA", (w * self.ss, h * self.ss), bg)

    def shape(self, polys, colour, matrix, evenodd=False):
        """Fills polygons (path units) through matrix (a, b, c, d, e, f: x' = a x + c y + e, y' = b x + d y + f).
        evenodd for glyph outlines, whose counters are separate contours."""
        from PIL import Image, ImageChops, ImageDraw
        SS = self.ss
        mask = Image.new("L", self.img.size, 0)
        draw = ImageDraw.Draw(mask)
        a, b, c, d, e, f = matrix
        if not evenodd:
            for poly in polys:
                draw.polygon([((a * x + c * y + e) * SS, (b * x + d * y + f) * SS) for x, y in poly], fill=255)
        else:
            # Non-zero winding as fonts use it: contours turning one way are ink (overlapping parts merge), the other
            # way are counters, cut out afterwards.
            def area(poly):
                return sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(poly, poly[1:] + poly[:1]))
            ink = max((p for p in polys), key=lambda p: abs(area(p)))
            sign = area(ink) > 0
            holes = Image.new("L", self.img.size, 0)
            hdraw = ImageDraw.Draw(holes)
            for poly in polys:
                pts = [((a * x + c * y + e) * SS, (b * x + d * y + f) * SS) for x, y in poly]
                (draw if (area(poly) > 0) == sign else hdraw).polygon(pts, fill=255)
            mask = ImageChops.subtract(mask, holes)
        self.composite(mask, colour)

    def composite(self, mask, colour):
        from PIL import Image
        r, g, b_, alpha = colour
        if alpha < 255:
            mask = mask.point(lambda v: v * alpha // 255)
        layer = Image.new("RGBA", self.img.size, (r, g, b_, 255))
        layer.putalpha(mask)
        self.img = Image.alpha_composite(self.img, layer)

    def round_rect(self, x, y, w, h, radius, colour):
        from PIL import Image, ImageDraw
        mask = Image.new("L", self.img.size, 0)
        SS = self.ss
        ImageDraw.Draw(mask).rounded_rectangle([x * SS, y * SS, (x + w) * SS - 1, (y + h) * SS - 1], radius=radius * SS, fill=255)
        self.composite(mask, colour)

    def squircle(self, cx, cy, half, n, colour, dy=0.0):
        pts = []
        for k in range(720):
            t = 2 * math.pi * k / 720
            ct, st = math.cos(t), math.sin(t)
            pts.append((cx + half * math.copysign(abs(ct) ** (2 / n), ct), cy + dy + half * math.copysign(abs(st) ** (2 / n), st)))
        self.shape([pts], colour, (1, 0, 0, 1, 0, 0))

    def result(self, mode="RGBA"):
        out = self.img.resize((self.w, self.h), self.Image.BOX)
        return out if mode == "RGBA" else out.convert(mode)


def hex_rgba(h: str, alpha=255):
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), alpha


def png_bytes(img) -> bytes:
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=False)
    return buf.getvalue()


def ico_bytes(frames) -> bytes:
    """An .ico with one PNG-compressed frame per size (Windows Vista and later read PNG frames at every size)."""
    data = [png_bytes(f) for f in frames]
    out = struct.pack("<HHH", 0, 1, len(frames))
    offset = 6 + 16 * len(frames)
    for img, blob in zip(frames, data):
        w, h = img.size
        out += struct.pack("<BBBBHHII", w % 256, h % 256, 0, 0, 1, 32, len(blob), offset)
        offset += len(blob)
    return out + b"".join(data)


def icns_bytes(images: dict) -> bytes:
    """An .icns from PNG entries keyed by OSType (ic11 = 32 px for 16@2x, …, ic10 = 1024 px)."""
    body = b"".join(k.encode() + struct.pack(">I", 8 + len(v)) + v for k, v in images.items())
    return b"icns" + struct.pack(">I", 8 + len(body)) + body


def bmp_bytes(img) -> bytes:
    buf = io.BytesIO()
    img.convert("RGB").save(buf, "BMP")
    return buf.getvalue()


def images(t: dict, symbol: str, en: dict) -> dict:
    """Every raster brand asset of the desktop, by path. Drawing rules: docs/design/desktop-phase1-foundation.html#icons."""
    sym = flatten(symbol)
    teal = hex_rgba(t["color"]["brand"]["teal"])
    white = (255, 255, 255, 255)
    out = {}

    def centred(px, width_px, extra_dy=0.0):
        s = width_px / 19.5  # the symbol is 19.5 units wide (x 2.25..21.75) and 16.5 high (y 6..22.5)
        return (s, 0, 0, s, px / 2 - 12 * s, px / 2 - 14.25 * s + extra_dy)

    def plate(px):
        c = Canvas(px, px)
        c.round_rect(0, 0, px, px, max(2, px * 0.22), teal)
        c.shape(sym, white, centred(px, px * 0.70))
        return c.result()

    # The app icon (.ico): exe, taskbar, Start, Alt+Tab, window title bars, the toast registration, the installer.
    out[DESKTOP / "Assets/josour.ico"] = ico_bytes([plate(px) for px in (16, 20, 24, 32, 48, 64, 256)])

    # The macOS icon: Apple's grid, an 824-pt squircle at 100,100 on 1024, the symbol 60 % of the plate wide.
    def mac_icon(px):
        k = px / 1024
        c = Canvas(px, px)
        c.squircle(512 * k, 512 * k, 412 * k, 4.2, (0, 0, 0, 36), dy=10 * k)
        c.squircle(512 * k, 512 * k, 412 * k, 4.2, teal)
        c.shape(sym, white, centred(px, 824 * 0.60 * k))
        return png_bytes(c.result())

    out[DESKTOP / "Assets/josour.icns"] = icns_bytes({
        "icp4": mac_icon(16), "icp5": mac_icon(32), "icp6": mac_icon(64), "ic07": mac_icon(128), "ic08": mac_icon(256),
        "ic09": mac_icon(512), "ic10": mac_icon(1024), "ic11": mac_icon(32), "ic12": mac_icon(64), "ic13": mac_icon(256), "ic14": mac_icon(512),
    })

    # The tray and menu-bar icon in four states (decision 7).
    broken = flatten("M4.5,15 A7.5,7.5 0 0,1 9.435,7.952 M14.565,7.952 A7.5,7.5 0 0,1 19.5,15")
    dots = flatten("M2.25,20.25a2.25,2.25 0 1,1 4.5,0a2.25,2.25 0 1,1 -4.5,0ZM17.25,20.25a2.25,2.25 0 1,1 4.5,0a2.25,2.25 0 1,1 -4.5,0Z")
    third = flatten("M19.5,5.25a2.25,2.25 0 1,1 4.5,0a2.25,2.25 0 1,1 -4.5,0Z")

    def band(points, width=3.0):
        """A stroked polyline (flat caps) as polygons, for the broken arch."""
        polys = []
        for line in points:
            left, right = [], []
            for k, (x, y) in enumerate(line):
                x0, y0 = line[max(0, k - 1)]
                x1, y1 = line[min(len(line) - 1, k + 1)]
                dx, dy = x1 - x0, y1 - y0
                n = math.hypot(dx, dy) or 1
                nx, ny = -dy / n * width / 2, dx / n * width / 2
                left.append((x + nx, y + ny))
                right.append((x - nx, y - ny))
            polys.append(left + right[::-1])
        return polys

    def state_glyph(c, state, colour, matrix):
        if state == "available":
            c.shape(sym, colour, matrix)
        elif state == "off":
            c.shape(sym, colour[:3] + (round(colour[3] * 0.42),), matrix)
        elif state == "unreachable":
            c.shape(band(broken), colour, matrix)
            c.shape(dots, colour, matrix)
        elif state == "session":
            c.shape(sym, colour, matrix)
            c.shape(third, colour, matrix)

    states = ("available", "off", "unreachable", "session")
    for state in states:
        for taskbar, colour in (("light", hex_rgba("#1A1A1A")), ("dark", white)):
            frames = []
            for px in (16, 20, 24, 32):
                c = Canvas(px, px)
                s = px / 24
                state_glyph(c, state, colour, (s, 0, 0, s, 0, -3 * s))
                frames.append(c.result())
            out[DESKTOP / f"Assets/Tray/{state}-{taskbar}.ico"] = ico_bytes(frames)
        # macOS: an 18-pt template image (black + alpha) at @2x; the system tints it.
        px = 36
        c = Canvas(px, px)
        s = (px * 15 / 18) / 19.5
        state_glyph(c, state, (0, 0, 0, 255), (s, 0, 0, s, px / 2 - 12 * s, px / 2 - 14.25 * s))
        out[DESKTOP / f"Assets/Tray/{state}-template.png"] = png_bytes(c.result())

    # The installer's wizard images (Inno Setup, modern style) at 100, 150 and 200 %.
    word = [p for d in en["wordmark"] for p in flatten(d)]
    for scale, (sw, sh), (lw, lh) in ((100, (55, 55), (164, 314)), (150, (83, 80), (246, 459)), (200, (110, 106), (328, 604))):
        small = Canvas(sw, sh, (255, 255, 255, 255))
        side = min(sw, sh)
        small.round_rect((sw - side) / 2, (sh - side) / 2, side, side, side * 0.22, teal)
        small.shape(sym, white, (side * 0.70 / 19.5, 0, 0, side * 0.70 / 19.5, sw / 2 - 12 * side * 0.70 / 19.5, sh / 2 - 14.25 * side * 0.70 / 19.5))
        out[INSTALLER_ART / f"wizard-small-{scale}.bmp"] = bmp_bytes(small.result())
        large = Canvas(lw, lh, teal)
        s = lw * 0.46 / 19.5
        large.shape(sym, white, (s, 0, 0, s, lw / 2 - 12 * s, lh * 0.36 - 14.25 * s))
        # The lock-up's wordmark ("Josour  جسور"), in white, under the symbol, fitted to 80 % of the width.
        xs = [x for poly in word for x, _ in poly]
        ys = [y for poly in word for _, y in poly]
        ws = lw * 0.80 / (max(xs) - min(xs))
        large.shape(word, white, (ws, 0, 0, ws, lw / 2 - (min(xs) + max(xs)) / 2 * ws, lh * 0.64 - (min(ys) + max(ys)) / 2 * ws), evenodd=True)
        out[INSTALLER_ART / f"wizard-{scale}.bmp"] = bmp_bytes(large.result())
    return out


def inputs_hash() -> str:
    h = hashlib.sha256()
    for path in [TOKENS, *sorted(LOGO.glob("*.svg")), Path(__file__)]:
        h.update(path.name.encode())
        h.update(path.read_bytes())
    h.update(RENDER_VERSION.encode())
    return h.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs instead of writing it")
    args = parser.parse_args()

    t = json.loads(TOKENS.read_text())
    symbol = re.search(r'<path d="([^"]+)"', (LOGO / "symbol-teal.svg").read_text()).group(1)
    en, ar = logo_parts(LOGO / "lockup-en-first-ltr.svg"), logo_parts(LOGO / "lockup-ar-first-rtl.svg")
    if en["symbol"] != symbol or ar["symbol"] != symbol:
        print("The lock-ups' symbol differs from symbol-teal.svg; refusing to guess which is right.", file=sys.stderr)
        return 1

    texts = {
        BRAND / "Theme/Tokens.axaml": brand_tokens_axaml(t),
        BRAND / "Controls/BrandGeometry.g.cs": brand_cs(symbol, en, ar),
        MOBILE / "Theme/Metrics.axaml": mobile_metrics_axaml(t),
        DESKTOP / "Theme/Metrics.axaml": desktop_metrics_axaml(t),
        DESKTOP / "Theme/FluentOverrides.axaml": desktop_fluent_axaml(t),
        **android_files(symbol, t),
    }
    stale = []
    rel = lambda p: str(p.relative_to(ROOT))
    if args.check:
        for path, content in texts.items():
            if not path.exists() or path.read_text() != content:
                stale.append(rel(path))
        if not STAMP.exists():
            stale.append(rel(STAMP))
        else:
            lines = STAMP.read_text().split("\n")
            if lines[0] != "inputs " + inputs_hash():
                stale.append(rel(STAMP) + " (the tokens, the logo or the generator changed)")
            for line in lines[1:]:
                if not line.strip():
                    continue
                digest, name = line.split("  ", 1)
                path = ROOT / name
                if not path.exists() or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
                    stale.append(name)
        if stale:
            print("Out of date: " + ", ".join(stale) + "\nRun python3 scripts/brand-theme.py", file=sys.stderr)
            return 1
        print(f"Checked {len(texts)} files and the brand images.")
        return 0

    for path, content in texts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    try:
        binaries = images(t, symbol, en)
    except ImportError:
        print("Drawing the images needs Pillow (python3 -m pip install pillow).", file=sys.stderr)
        return 1
    stamp = ["inputs " + inputs_hash()]
    for path, blob in sorted(binaries.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(blob)
        stamp.append(f"{hashlib.sha256(blob).hexdigest()}  {rel(path)}")
    STAMP.write_text("\n".join(stamp) + "\n")
    print(f"Wrote {len(texts)} files and {len(binaries)} images.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
