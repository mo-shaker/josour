# ------------------------------------------------------------------------------------------------------ path to polygons
def flatten(d: str):
    """SVG path data (M L H V Q C A Z, absolute and relative) to closed polygons in path units."""
    tokens = re.findall(r"[MLHVQCAZmlhvqcaz]|-?\d*\.?\d+(?:e-?\d+)?", d)
    polys, cur, i = [], [], 0
    x = y = sx = sy = 0.0
    cmd = None

    def num():
        nonlocal i
        v = float(tokens[i])
        i += 1
        return v

    while i < len(tokens):
        if re.match(r"[A-Za-z]", tokens[i]):
            cmd = tokens[i]
            i += 1
            if cmd in "Zz":
                if cur:
                    polys.append(cur)
                cur, x, y = [], sx, sy
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            if cur:
                polys.append(cur)
            cur, sx, sy = [(x, y)], x, y
            cmd = "l" if rel else "L"
        elif c == "L":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            cur.append((x, y))
        elif c == "H":
            nx = num()
            x = x + nx if rel else nx
            cur.append((x, y))
        elif c == "V":
            ny = num()
            y = y + ny if rel else ny
            cur.append((x, y))
        elif c in "QC":
            pts = [num() for _ in range(4 if c == "Q" else 6)]
            if rel:
                pts = [p + (x if k % 2 == 0 else y) for k, p in enumerate(pts)]
            ctrl = [(x, y)] + [(pts[k], pts[k + 1]) for k in range(0, len(pts), 2)]
            for s in range(1, 17):
                u = s / 16
                if c == "Q":
                    (x0, y0), (x1, y1), (x2, y2) = ctrl
                    px = (1 - u) ** 2 * x0 + 2 * (1 - u) * u * x1 + u * u * x2
                    py = (1 - u) ** 2 * y0 + 2 * (1 - u) * u * y1 + u * u * y2
                else:
                    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = ctrl
                    px = (1 - u) ** 3 * x0 + 3 * (1 - u) ** 2 * u * x1 + 3 * (1 - u) * u * u * x2 + u ** 3 * x3
                    py = (1 - u) ** 3 * y0 + 3 * (1 - u) ** 2 * u * y1 + 3 * (1 - u) * u * u * y2 + u ** 3 * y3
                cur.append((px, py))
            x, y = ctrl[-1]
        elif c == "A":
            rx, ry, rot, large, sweep, nx, ny = num(), num(), num(), num(), num(), num(), num()
            ex, ey = (x + nx, y + ny) if rel else (nx, ny)
            cur.extend(arc_points(x, y, rx, ry, rot, int(large), int(sweep), ex, ey))
            x, y = ex, ey
    if cur:
        polys.append(cur)
    return polys


def arc_points(x1, y1, rx, ry, phi, fa, fs, x2, y2):
    """The endpoint-to-centre conversion of SVG 1.1 appendix F.6, sampled every 2 degrees."""
    cp, sp_ = math.cos(math.radians(phi)), math.sin(math.radians(phi))
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    x1p, y1p = cp * dx + sp_ * dy, -sp_ * dx + cp * dy
    lam = (x1p ** 2) / (rx ** 2) + (y1p ** 2) / (ry ** 2)
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num_ = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p
    den = rx * rx * y1p * y1p + ry * ry * x1p * x1p
    co = math.sqrt(max(0.0, num_ / den)) * (-1 if fa == fs else 1)
    cxp, cyp = co * rx * y1p / ry, -co * ry * x1p / rx
    cx, cy = cp * cxp - sp_ * cyp + (x1 + x2) / 2, sp_ * cxp + cp * cyp + (y1 + y2) / 2

    def ang(ux, uy, vx, vy):
        a = math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)
        return a

    t1 = ang(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dt = ang((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry)
    if not fs and dt > 0:
        dt -= 2 * math.pi
    elif fs and dt < 0:
        dt += 2 * math.pi
    n = max(2, int(abs(dt) / math.radians(2)))
    out = []
    for k in range(1, n + 1):
        t = t1 + dt * k / n
        out.append((cx + rx * math.cos(t) * cp - ry * math.sin(t) * sp_, cy + rx * math.cos(t) * sp_ + ry * math.sin(t) * cp))
    return out


