#!/usr/bin/env python3
"""Generate the phone's theme and brand resources from their two sources of truth.

    python3 scripts/mobile-theme.py           # writes the files below
    python3 scripts/mobile-theme.py --check   # fails if any of them is out of date

Inputs
  docs/design/mobile-tokens.json   the approved design tokens (Phase 1, docs/design/mobile-phase1-foundation.html)
  1-qantara/*.svg                  the logo files, used as they are (path data copied, never redrawn)

Outputs (all marked "generated"; edit the inputs, not these)
  client/src/Josour.Mobile/Theme/Tokens.axaml          colours (ThemeDictionaries Light/Dark), radii, spacing, sizes
  client/src/Josour.Mobile/Controls/BrandGeometry.g.cs the symbol and both lock-ups as path data
  client/src/Josour.Android/Resources/...              launcher foreground/monochrome, notification icon, splash icon,
                                                       colours for values and values-night
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "docs/design/mobile-tokens.json"
LOGO = ROOT / "1-qantara"
MOBILE = ROOT / "client/src/Josour.Mobile"
ANDROID = ROOT / "client/src/Josour.Android/Resources"
HEADER = "generated by scripts/mobile-theme.py from docs/design/mobile-tokens.json and 1-qantara/; do not edit"

# The symbol's bounding box is x 2.25..21.75, y 6..22.5: centred in a 108 dp adaptive canvas at 2.5x its farthest point
# (the outer edge of a dot) is 29.6 dp from the centre, inside the 33 dp safe radius.
LAUNCHER = {"scale": 2.5, "tx": 24.0, "ty": 18.375}
# The splash: a 104 dp teal disc carrying the symbol 70 dp wide, drawn in a 108-unit viewport that Android shows at
# 288 dp (Android 12+ "icon without background") and that the pre-12 window background shows at the same size.
SPLASH = {"size_dp": 288, "disc_r": 19.5, "scale": 1.354, "tx": 37.75, "ty": 34.71}


def argb(hex_rgb: str, alpha: str = "FF") -> str:
    return "#" + alpha + hex_rgb.lstrip("#").upper()


def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def tokens_axaml(t: dict) -> str:
    def theme(mode: str) -> str:
        c = t["color"][mode]
        teal = t["color"]["teal"]
        colours = {
            "Canvas": c["canvas"], "Surface": c["surface"], "SurfaceRaised": c["surfaceRaised"], "SurfaceSunken": c["surfaceSunken"],
            "Border": c["border"], "BorderStrong": c["borderStrong"],
            "Text": c["text"], "TextSecondary": c["textSecondary"], "TextTertiary": c["textTertiary"], "TextDisabled": c["textDisabled"],
            "Primary": c["primary"], "PrimaryHover": c["primaryHover"], "PrimaryPressed": c["primaryPressed"], "OnPrimary": c["onPrimary"],
            "PrimaryContainer": c["primaryContainer"], "OnPrimaryContainer": c["onPrimaryContainer"], "Focus": c["focus"],
            "MotifActive": c["motif"]["active"], "MotifIdle": c["motif"]["idle"], "MotifDotOff": c["motif"]["dotOff"],
            "LogoSymbol": c["logo"]["symbol"], "LogoWordmark": c["logo"]["wordmark"],
        }
        for role in ("success", "warning", "danger", "info"):
            for part, key in (("fg", "Fg"), ("container", "Container"), ("border", "Border")):
                colours[pascal(role) + key] = c[role][part]
        lines = [f'    <ResourceDictionary x:Key="{pascal(mode)}">']
        for name, value in colours.items():
            lines.append(f'      <Color x:Key="Josour.Color.{name}">{argb(value)}</Color>')
            lines.append(f'      <SolidColorBrush x:Key="Josour.Brush.{name}" Color="{argb(value)}" />')
        # Fluent's accent, so stock controls (selection, focus, progress) carry the brand teal too.
        if mode == "light":
            accent = [c["primary"], c["primaryHover"], c["primaryPressed"], teal["950"], teal["600"], teal["500"], teal["400"]]
            shadow = t["elevation"]["light"]
            lines.append(f'      <BoxShadows x:Key="Josour.Elevation.1">{shadow["1"]}</BoxShadows>')
            lines.append(f'      <BoxShadows x:Key="Josour.Elevation.2">{shadow["2"]}</BoxShadows>')
            lines.append(f'      <BoxShadows x:Key="Josour.Elevation.3">{shadow["3"]}</BoxShadows>')
        else:
            accent = [c["primary"], teal["500"], teal["600"], teal["700"], c["primaryHover"], teal["200"], teal["100"]]
            for level in ("1", "2", "3"):
                lines.append(f'      <BoxShadows x:Key="Josour.Elevation.{level}">0 0 0 0 #00000000</BoxShadows>')
        for name, value in zip(("", "Dark1", "Dark2", "Dark3", "Light1", "Light2", "Light3"), accent):
            lines.append(f'      <Color x:Key="SystemAccentColor{name}">{argb(value)}</Color>')
        lines.append("    </ResourceDictionary>")
        return "\n".join(lines)

    out = [
        f"<!-- {HEADER} -->",
        '<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        "  <ResourceDictionary.ThemeDictionaries>",
        theme("light"),
        theme("dark"),
        "  </ResourceDictionary.ThemeDictionaries>",
        "",
        "  <!-- The brand colours themselves, the same in both themes (the launcher icon, the splash disc). -->",
        f'  <SolidColorBrush x:Key="Josour.Brush.BrandTeal" Color="{argb(t["color"]["brand"]["teal"])}" />',
        f'  <SolidColorBrush x:Key="Josour.Brush.BrandWhite" Color="{argb(t["color"]["brand"]["white"])}" />',
        "",
        '  <FontFamily x:Key="Josour.Font">fonts:Josour#Readex Pro</FontFamily>',
    ]
    for name, value in t["radius"].items():
        out.append(f'  <CornerRadius x:Key="Josour.Radius.{pascal(name)}">{value}</CornerRadius>')
    for name, value in t["space"].items():
        out.append(f'  <x:Double x:Key="Josour.Space.{pascal(name)}">{value}</x:Double>')
    sizes = t["size"]
    for name in ("touchTarget", "buttonHeight", "inputHeight", "tabBarHeight", "presenceDot", "badge", "focusRing"):
        out.append(f'  <x:Double x:Key="Josour.Size.{pascal(name)}">{sizes[name]}</x:Double>')
    for name, value in sizes["icon"].items():
        out.append(f'  <x:Double x:Key="Josour.Size.Icon{pascal(name)}">{value}</x:Double>')
    for name, value in sizes["motif"].items():
        if name != "strokeRatio":
            out.append(f'  <x:Double x:Key="Josour.Size.Motif{pascal(name)}">{value}</x:Double>')
    out.append("</ResourceDictionary>")
    return "\n".join(out) + "\n"


def logo_parts(svg: Path) -> dict:
    text = svg.read_text()
    parts = {"wordmark": [], "symbol": None, "transform": None}
    group = re.search(r'<g transform="translate\(([\d.]+),([\d.]+)\) scale\(([\d.]+)\)">\s*<path d="([^"]+)" fill="#0E7490"/>', text)
    if group:
        parts["transform"] = tuple(float(v) for v in group.group(1, 2, 3))
        parts["symbol"] = group.group(4)
    for match in re.finditer(r'<path d="([^"]+)" fill="#14232B"/>', text):
        parts["wordmark"].append(match.group(1))
    return parts


def brand_cs(symbol: str, en: dict, ar: dict) -> str:
    def lit(s: str) -> str:
        return '"' + s + '"'

    def lockup(name: str, p: dict) -> str:
        tx, ty, sc = p["transform"]
        return (f"    /// <summary>The {name} lock-up, 674×200: the wordmark paths and where the symbol sits.</summary>\n"
                f"    public static readonly LockupGeometry {name} = new(\n"
                f"        new[]\n        {{\n" + "".join(f"            {lit(d)},\n" for d in p["wordmark"]) +
                f"        }},\n        SymbolX: {tx}, SymbolY: {ty}, SymbolScale: {sc});\n")

    return (f"// <auto-generated>{HEADER}</auto-generated>\n"
            "namespace Josour.Mobile.Controls;\n\n"
            "/// <summary>A lock-up: its wordmark paths (ink) and the symbol's placement (translate, then scale).</summary>\n"
            "public sealed record LockupGeometry(string[] Wordmark, double SymbolX, double SymbolY, double SymbolScale)\n"
            "{\n    public const double Width = 674;\n    public const double Height = 200;\n}\n\n"
            "/// <summary>The qantara mark from <c>1-qantara/</c>, path for path. Never redrawn: regenerate instead.</summary>\n"
            "public static class BrandGeometry\n{\n"
            "    /// <summary>The symbol on its 24-unit grid: the arch (outer r 9, inner r 6 about 12,15) and two dots of r 2.25.</summary>\n"
            f"    public const string Symbol = {lit(symbol)};\n\n"
            + lockup("EnglishFirst", en) + "\n" + lockup("ArabicFirst", ar) + "}\n")


def android_vector(width_dp: float, viewport: float, body: str, comment: str) -> str:
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} ({HEADER}) -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'        android:width="{width_dp:g}dp" android:height="{width_dp:g}dp"\n'
            f'        android:viewportWidth="{viewport:g}" android:viewportHeight="{viewport:g}">\n{body}</vector>\n')


def android_files(symbol: str, t: dict) -> dict:
    tr = LAUNCHER
    group = (f'  <group android:translateX="{tr["tx"]}" android:translateY="{tr["ty"]}" '
             f'android:scaleX="{tr["scale"]}" android:scaleY="{tr["scale"]}">\n'
             f'    <path android:fillColor="#FFFFFFFF" android:pathData="{symbol}" />\n  </group>\n')
    sp = SPLASH
    splash = (f'  <path android:fillColor="@color/josour_brand_teal" android:pathData="M54,{54 - sp["disc_r"]}a{sp["disc_r"]},{sp["disc_r"]} 0 1,1 0,{2 * sp["disc_r"]}a{sp["disc_r"]},{sp["disc_r"]} 0 1,1 0,{-2 * sp["disc_r"]}Z" />\n'
              f'  <group android:translateX="{sp["tx"]}" android:translateY="{sp["ty"]}" android:scaleX="{sp["scale"]}" android:scaleY="{sp["scale"]}">\n'
              f'    <path android:fillColor="#FFFFFFFF" android:pathData="{symbol}" />\n  </group>\n')
    light, dark = t["color"]["light"], t["color"]["dark"]

    def colours(mode: dict, night: bool) -> str:
        return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {HEADER} -->\n<resources>\n'
                f'  <color name="josour_brand_teal">{argb(t["color"]["brand"]["teal"])}</color>\n'
                f'  <color name="josour_canvas">{argb(mode["canvas"])}</color>\n'
                f'  <color name="josour_surface">{argb(mode["surface"])}</color>\n'
                f'  <color name="josour_primary">{argb(mode["primary"])}</color>\n'
                f'  <bool name="josour_light_bars">{"false" if night else "true"}</bool>\n'
                "</resources>\n")

    return {
        ANDROID / "drawable/ic_launcher_foreground.xml": android_vector(108, 108, group, "Launcher foreground: the symbol, white, in the 66 dp safe zone"),
        ANDROID / "drawable/ic_launcher_monochrome.xml": android_vector(108, 108, group, "Themed icon (Android 13+): the same symbol, tinted by the system"),
        ANDROID / "drawable/ic_stat_josour.xml": android_vector(24, 24, f'  <path android:fillColor="#FFFFFFFF" android:pathData="{symbol}" />\n',
                                                                "Notification small icon: the symbol as a one-colour silhouette"),
        ANDROID / "drawable/splash_icon.xml": android_vector(sp["size_dp"], 108, splash, "Splash: a teal disc with the white symbol, also the pre-12 window background"),
        ANDROID / "values/colors.xml": colours(light, False),
        ANDROID / "values-night/colors.xml": colours(dark, True),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs instead of writing it")
    args = parser.parse_args()

    t = json.loads(TOKENS.read_text())
    symbol = re.search(r'<path d="([^"]+)"', (LOGO / "symbol-teal.svg").read_text()).group(1)
    en, ar = logo_parts(LOGO / "lockup-en-first-ltr.svg"), logo_parts(LOGO / "lockup-ar-first-rtl.svg")
    if en["symbol"] != symbol or ar["symbol"] != symbol:
        print("The lock-ups' symbol differs from symbol-teal.svg; refusing to guess which is right.", file=sys.stderr)
        return 1

    files = {
        MOBILE / "Theme/Tokens.axaml": tokens_axaml(t),
        MOBILE / "Controls/BrandGeometry.g.cs": brand_cs(symbol, en, ar),
        **android_files(symbol, t),
    }
    stale = []
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Out of date: " + ", ".join(stale) + "\nRun python3 scripts/mobile-theme.py", file=sys.stderr)
        return 1
    print(("Checked " if args.check else "Wrote ") + str(len(files)) + " files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
