using Avalonia;
using Avalonia.Controls;
using Avalonia.Data;
using Avalonia.Input;
using Avalonia.Platform;
using Microsoft.Extensions.Logging;
using Josour.App.ViewModels;

namespace Josour.App.Services;

/// <summary>
/// The notification-area icon (Avalonia's <see cref="TrayIcon"/>: the Windows tray and the macOS menu bar), and on macOS the
/// app menu. Menu items bind straight to <see cref="MainViewModel"/> so the tray, the hero's switch and the settings share
/// one state. Must be initialised on the UI thread.
/// <para>
/// The icon shows the state in four shapes (Phase 1 decision 7: available, not available, can't reach the server, in a
/// session), and the menu's first, greyed line says it in words. On Windows the glyph follows the taskbar (ink or white);
/// on macOS it is a template image the system tints. The images are generated by scripts/brand-theme.py.
/// </para>
/// </summary>
public sealed class TrayService : IDisposable
{
    private readonly MainViewModel _viewModel;
    private readonly ILogger<TrayService> _logger;
    private TrayIcon? _icon;
    private TrayIcons? _icons;
    private NativeMenuItem? _stateItem;
    private NativeMenuItem? _adminItem;

    public TrayService(MainViewModel viewModel, ILogger<TrayService> logger)
    {
        _viewModel = viewModel;
        _logger = logger;
    }

    public void Initialize()
    {
        if (_icon is not null)
        {
            return;
        }

        var application = Application.Current;
        if (application is null)
        {
            _logger.LogWarning("No application instance; the tray icon was not created");
            return;
        }

        _icon = new TrayIcon
        {
            ToolTipText = _viewModel.TrayTooltip,
            Icon = LoadIcon(_viewModel.TrayState),
            Menu = BuildMenu(),
            IsVisible = true,
        };

        if (OperatingSystem.IsMacOS())
        {
            // Black plus alpha, tinted by the system for a light or dark menu bar and for the open menu.
            MacOSProperties.SetIsTemplateIcon(_icon, true);
            NativeMenu.SetMenu(application, BuildAppMenu());
        }

        // Avalonia raises Clicked for a single click; a menu-bar item with a menu opens the menu on macOS instead.
        _icon.Clicked += (_, _) => _viewModel.ShowWindowCommand.Execute(null);
        _viewModel.PropertyChanged += OnViewModelPropertyChanged;

        // The taskbar's light or dark setting can change while the app runs; Avalonia reports it with the colour values.
        if (application.PlatformSettings is { } settings)
        {
            settings.ColorValuesChanged += (_, _) => UiThread.Post(RefreshIcon);
        }

        _icons = new TrayIcons { _icon };
        TrayIcon.SetIcons(application, _icons);
        _logger.LogInformation("Tray icon created");
    }

    /// <summary>The tooltip, the icon and the state line are not bindable on a tray icon (no visual tree), so they are pushed.</summary>
    private void OnViewModelPropertyChanged(object? sender, System.ComponentModel.PropertyChangedEventArgs e)
    {
        switch (e.PropertyName)
        {
            case nameof(MainViewModel.TrayTooltip):
                UiThread.Post(() =>
                {
                    if (_icon is not null)
                    {
                        _icon.ToolTipText = _viewModel.TrayTooltip;
                    }
                });
                break;
            case nameof(MainViewModel.TrayState):
                UiThread.Post(RefreshIcon);
                break;
            case nameof(MainViewModel.TrayStateText):
                UiThread.Post(() =>
                {
                    if (_stateItem is not null)
                    {
                        _stateItem.Header = _viewModel.TrayStateText;
                    }
                });
                break;
            case nameof(MainViewModel.IsAdmin):
                UiThread.Post(() =>
                {
                    if (_adminItem is not null)
                    {
                        _adminItem.IsVisible = _viewModel.IsAdmin;
                    }
                });
                break;
        }
    }

    private void RefreshIcon()
    {
        if (_icon is not null)
        {
            _icon.Icon = LoadIcon(_viewModel.TrayState);
        }
    }

    private NativeMenu BuildMenu()
    {
        var menu = new NativeMenu();

        // The state in words, first and greyed: the icon never carries it alone.
        _stateItem = new NativeMenuItem(_viewModel.TrayStateText) { IsEnabled = false };
        menu.Add(_stateItem);
        menu.Add(new NativeMenuItemSeparator());
        menu.Add(Item(Strings.TrayShowWindow, _viewModel.ShowWindowCommand));
        menu.Add(new NativeMenuItemSeparator());
        menu.Add(Toggle(Strings.TrayAvailableForRequests, nameof(MainViewModel.IsAvailable)));
        menu.Add(Toggle(Strings.TrayStartAtLogin, nameof(MainViewModel.StartAtLogin)));
        menu.Add(new NativeMenuItemSeparator());
        menu.Add(Item(Strings.TraySettings, _viewModel.ShowSettingsCommand));
        menu.Add(Item(Strings.TrayAbout, _viewModel.ShowAboutCommand));
        menu.Add(Item(Strings.TrayRepairInternet, _viewModel.RepairInternetSettingsCommand));

        // Listed only for an administrator (the server enforces the role whatever the menu shows).
        _adminItem = Item(Strings.TrayAdmin, _viewModel.ShowAdminCommand);
        _adminItem.IsVisible = _viewModel.IsAdmin;
        menu.Add(_adminItem);

        if (_viewModel.IsDebugMenuVisible)
        {
            var debug = new NativeMenuItem(Strings.TrayDebug)
            {
                Menu = new NativeMenu { Item(Strings.TraySimulateIncomingRequest, _viewModel.SimulateIncomingRequestCommand) },
            };
            menu.Add(new NativeMenuItemSeparator());
            menu.Add(debug);
        }

        menu.Add(new NativeMenuItemSeparator());
        menu.Add(Item(Strings.TraySignOut, _viewModel.AskSignOutCommand));
        // Exit asks first while sharing or in a session (Phase 1 decision 11).
        menu.Add(Item(OperatingSystem.IsMacOS() ? Strings.DesktopQuitApp : Strings.TrayExit, _viewModel.AskQuitCommand));
        return menu;
    }

    /// <summary>macOS's app menu (Phase 1 decision 14): About, Settings (⌘,), User management, Sign out, Hide, Quit (⌘Q).</summary>
    private NativeMenu BuildAppMenu()
    {
        var command = KeyModifiers.Meta;
        var admin = Item(Strings.TrayAdmin, _viewModel.ShowAdminCommand);
        admin.IsVisible = _viewModel.IsAdmin;
        _viewModel.PropertyChanged += (_, e) =>
        {
            if (e.PropertyName == nameof(MainViewModel.IsAdmin))
            {
                UiThread.Post(() => admin.IsVisible = _viewModel.IsAdmin);
            }
        };

        var josour = new NativeMenu
        {
            Item(Strings.AboutWindowTitle, _viewModel.ShowAboutCommand),
            new NativeMenuItemSeparator(),
            new NativeMenuItem(Strings.TraySettings) { Command = _viewModel.ShowSettingsCommand, Gesture = new KeyGesture(Key.OemComma, command) },
            admin,
            new NativeMenuItemSeparator(),
            Item(Strings.TraySignOut, _viewModel.AskSignOutCommand),
            new NativeMenuItemSeparator(),
            new NativeMenuItem(Strings.DesktopQuitApp) { Command = _viewModel.AskQuitCommand, Gesture = new KeyGesture(Key.Q, command) },
        };
        return new NativeMenu { new NativeMenuItem(Strings.AppName) { Menu = josour } };
    }

    private static NativeMenuItem Item(string header, System.Windows.Input.ICommand command) =>
        new(header) { Command = command };

    /// <summary>A checkable item bound two-way, so ticking it in the tray is the same act as toggling it in the window.</summary>
    private NativeMenuItem Toggle(string header, string propertyPath)
    {
        var item = new NativeMenuItem(header) { ToggleType = NativeMenuItemToggleType.CheckBox };
        item.Bind(
            NativeMenuItem.IsCheckedProperty,
            new Binding(propertyPath) { Source = _viewModel, Mode = BindingMode.TwoWay });
        return item;
    }

    /// <summary>The generated image for a state: a template PNG on macOS, an .ico for the taskbar's theme elsewhere.</summary>
    public static string IconUri(TrayIconState state, bool mac, bool lightTaskbar)
    {
        var name = state switch
        {
            TrayIconState.Available => "available",
            TrayIconState.Off => "off",
            TrayIconState.Unreachable => "unreachable",
            _ => "session",
        };
        return mac
            ? $"avares://Josour/Assets/Tray/{name}-template.png"
            : $"avares://Josour/Assets/Tray/{name}-{(lightTaskbar ? "light" : "dark")}.ico";
    }

    private static WindowIcon LoadIcon(TrayIconState state) =>
        new(AssetLoader.Open(new Uri(IconUri(state, OperatingSystem.IsMacOS(), TaskbarTheme.IsLight))));

    public void Dispose()
    {
        _viewModel.PropertyChanged -= OnViewModelPropertyChanged;
        if (_icon is not null)
        {
            _icon.IsVisible = false;
            _icon.Dispose();
            _icon = null;
        }

        _icons = null;
    }
}
