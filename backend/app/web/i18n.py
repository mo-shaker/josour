def translate(key: str, lang: str, **values: object) -> str:
    """The text for ``key``; the key itself when it is unknown, so a gap shows up as a key on
    the page rather than as nothing."""
    pair = STRINGS.get(key)
    if pair is None:
        return key
    text = pair[0] if lang == "ar" else pair[1]
    return text.format(**values) if values else text
